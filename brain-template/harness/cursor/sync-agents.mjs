// Generates the user/Cursor copies of the {{BRAIN_NAME}} subagents from the canonical .claude/agents/<name>.md (the only real
// definitions; regenerated on every run, so no drift).
//   .cursor/agents/      ({{BRAIN_NAME}}, Cursor project): every agent. Cursor reads .claude/agents too, but there
//                        `model: opus` is not a Cursor model id and `tools:` is ignored; the override (same name: .cursor/
//                        wins) sets `model: inherit` and `readonly: true` when the agent has no Edit/Write tool and
//                        no shell (Bash): Cursor's readonly mode blocks the shell too.
//   ~/.cursor/agents/    (Cursor user level, every project): same pointer as above.
//   ~/.claude/agents/    (Claude Code user level, every project): canonical file verbatim (frontmatter and full body,
//                        2026-10-13: a pointer body cost the subagent an extra read before starting) + the marker and one
//                        line on relative brain paths. In {{BRAIN_NAME}} the project agent of the same name wins (both harnesses).
// User level only from the main checkout (or --home); no canonical agents = exit 2, nothing touched.
// Idempotent. A file without the "Generated by sync-agents.mjs" marker is never overwritten or removed: reported as conflict.
// Usage: node harness/cursor/sync-agents.mjs [--check] [--root <{{BRAIN_NAME}} dir>] [--home <home dir, tests>]
//   --check: writes nothing, prints what is missing/stale/orphan/conflict, exit 1 if any (used by brain-lint §6).
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { brainRoot } from '../../ops/tools/brain-root.mjs';

const argv = process.argv.slice(2);
const opt = n => argv.includes(n) ? argv[argv.indexOf(n) + 1] : undefined;
const root = path.resolve(opt('--root') ?? brainRoot(import.meta.url));
const home = path.resolve(opt('--home') ?? os.homedir());
const check = argv.includes('--check');
const src = path.join(root, '.claude', 'agents');
const canonical = '{{BRAIN}}/.claude/agents';
// The compared agents (harness/compare/lib.mjs AGENTS) save their final report where capture.mjs looks for it (2026-10-12).
const COMPARED = new Set(['reviewer', 'code-investigator', 'prod-log-reader']);
const ANSWERS = '{{BRAIN}}/ops/state/compare/answers';
const MARK = /Generated by (?:harness\/cursor\/)?sync-agents\.mjs/; // old marker too, so old files count as generated
// User level is global: only from the main checkout (pointers name its files), never from a worktree's unmerged agents.
const userLevel = opt('--home') !== undefined || path.resolve(root).toLowerCase() === path.resolve(canonical, '..', '..').toLowerCase();
const targets = [
  { dir: path.join(root, '.cursor', 'agents'), show: '.cursor/agents', kind: 'cursor', user: false },
  ...(userLevel ? [
    { dir: path.join(home, '.cursor', 'agents'), show: '~/.cursor/agents', kind: 'cursor', user: true },
    { dir: path.join(home, '.claude', 'agents'), show: '~/.claude/agents', kind: 'claude', user: true },
  ] : []),
];
const srcFiles = fs.existsSync(src) ? fs.readdirSync(src).filter(f => f.endsWith('.md')) : [];
if (!srcFiles.length) { console.error(`no agents in ${src}: wrong --root? Nothing written.`); process.exit(2); } // else every pointer would be an orphan
const pointer = (name, f) => [
  `<!-- Generated by sync-agents.mjs ({{BRAIN_NAME}} harness/cursor/) from .claude/agents/${f}, do not edit: change that file and rerun. -->`,
  '',
  `You are the \`${name}\` subagent of {{OWNER}}'s {{BRAIN_NAME}} brain. Before anything else read \`${canonical}/${f}\` and`,
  'follow its instructions exactly. Brain paths it gives as relative (me.md, ops/, rules/...) are under',
  '`{{BRAIN}}/`.',
];

const want = new Map(targets.map(t => [t, new Map()]));
for (const f of srcFiles) {
  const text = fs.readFileSync(path.join(src, f), 'utf8').replace(/\r\n/g, '\n');
  const fmBlock = text.match(/^---\n[\s\S]*?\n---\n/)?.[0] ?? '';
  const fm = fmBlock.slice(4, -5);
  const field = k => {
    const m = fm.match(new RegExp(`^${k}:[ \\t]*(.*)$((?:\\n[ \\t]+.*)*)`, 'm'));
    if (!m) return '';
    return (/^[>|][-+]?$/.test(m[1].trim()) ? m[2] : `${m[1]}${m[2]}`).replace(/\s+/g, ' ').trim(); // YAML block or folded
  };
  const name = field('name') || f.replace(/\.md$/, '');
  const tools = field('tools'); // no tools line = every tool in Claude, so not read-only
  // readonly only without write tools AND without a shell: Cursor runs a readonly subagent in Ask mode, which blocks
  // every shell command, so a review agent could not even run `git diff` (seen 2026-10-10; Owner: readonly false for them).
  const readonly = tools !== '' && !/\b(Edit|Write|MultiEdit|NotebookEdit|Bash|PowerShell)\b/.test(tools);
  const cursor = [
    '---',
    `name: ${name}`,
    `description: ${JSON.stringify(field('description'))}`, // quoted: the text has ": " and quotes (valid YAML)
    'model: inherit',
    `readonly: ${readonly}`,
    '---',
    '',
    ...pointer(name, f),
    'Ignore its frontmatter (model, tools): in Cursor they come from this file. Claude-only tools it names',
    '(SubagentHandback, ToolSearch, mcp__ccd_*) do not exist here: return your final report as your last message.',
    ...(COMPARED.has(name) ? [
      'Right before that last message, also write the same final report, verbatim, to a new file',
      `\`${ANSWERS}/${name}-<any unique suffix>.md\`, whose first lines are the first 3 non-empty lines of your task`,
      'verbatim, one per line, each with `Task: ` in front (fewer if the task is shorter), then the report (the',
      'Cursor/Opus comparison reads it: in second-brain app chats Cursor does not hand a subagent\'s answer to the hooks).',
    ] : []),
    '',
  ].join('\n');
  const claude = [fmBlock.trimEnd(), '',
    `<!-- Generated by sync-agents.mjs ({{BRAIN_NAME}} harness/cursor/) from .claude/agents/${f}, do not edit: change that file and rerun. -->`,
    'Brain paths given as relative below (me.md, ops/, rules/...) are under `{{BRAIN}}/`.', '',
    text.slice(fmBlock.length).trim(), ''].join('\n');
  for (const t of targets) want.get(t).set(`${name}.md`, t.kind === 'claude' ? claude : cursor);
}

const issues = [], writes = [], removes = [];
for (const t of targets) {
  const w = want.get(t);
  const have = fs.existsSync(t.dir) ? fs.readdirSync(t.dir).filter(f => f.endsWith('.md')) : [];
  for (const [f, text] of w) {
    const p = path.join(t.dir, f);
    const cur = fs.existsSync(p) ? fs.readFileSync(p, 'utf8').replace(/\r\n/g, '\n') : null;
    if (cur === text) continue;
    if (cur !== null && !MARK.test(cur)) { issues.push(`conflict: ${t.show}/${f} (not generated: left untouched, rename or remove it)`); continue; }
    issues.push(`${cur === null ? 'missing' : 'stale'}: ${t.show}/${f}`);
    writes.push([p, text]);
  }
  for (const f of have) if (!w.has(f) && MARK.test(fs.readFileSync(path.join(t.dir, f), 'utf8'))) {
    issues.push(`orphan: ${t.show}/${f}`);
    removes.push(path.join(t.dir, f));
  }
}

if (check) { console.log(issues.join('\n') || 'ok'); process.exit(issues.length ? 1 : 0); }
for (const [p, text] of writes) { fs.mkdirSync(path.dirname(p), { recursive: true }); fs.writeFileSync(p, text); }
for (const p of removes) fs.unlinkSync(p);
const conflicts = issues.filter(i => i.startsWith('conflict'));
console.log(writes.length + removes.length ? `updated:\n${issues.filter(i => !i.startsWith('conflict')).join('\n')}` : 'already in sync');
if (conflicts.length) { console.log(`not touched:\n${conflicts.join('\n')}`); process.exit(1); }
