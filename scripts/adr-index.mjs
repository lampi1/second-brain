// Regenerates docs/adr/README.md, the one-line-per-ADR index (number, title, status), from the ADR files themselves,
// so agents and contributors find the current decision for a topic without opening every file. Run by hand after
// adding or changing an ADR: `node scripts/adr-index.mjs` (writes the index) or `node scripts/adr-index.mjs --check`
// (exit 1 when the index is stale or two ADRs share a number). No dependencies; read only except for the index file.
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const dir = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'docs', 'adr');
const out = path.join(dir, 'README.md');

/** The status of an ADR, from the paragraph that holds the first "Status:" in its header (the lines before its first
 *  "## " section): "superseded by N" when the whole record is, otherwise its state word plus the records that replace
 *  parts of it ("superseded/replaced/removed by ADR N", read up to the record's own "Supersedes", "Builds on",
 *  "Amends", "Amended by"). */
function statusOf(header) {
  const at = header.search(/Status:/);
  if (at < 0) return 'not stated';
  const para = header.slice(at + 'Status:'.length).split(/\n\s*\n/)[0].replace(/\s+/g, ' ').trim();
  const whole = /^superseded by ADR (\d{4})/i.exec(para);
  if (whole) return `superseded by ${whole[1]}`;
  const own = para.split(/\b(?:Supersedes|supersedes|Builds on|Amends|Amended by|Replaces)\b/)[0];
  const from = own.search(/\b(?:superseded|replaced|removed)\b/i);
  const by = from < 0 ? [] : [...new Set([...own.slice(from).matchAll(/\b(0\d{3})\b/g)].map(m => m[1]))];
  const state = /^partly superseded/i.test(own) ? own.slice(own.indexOf(';') + 1).trim() : own;
  const word = /^[A-Za-z]+/.exec(state)?.[0].toLowerCase() ?? 'not stated';
  return by.length ? `${word}, partly superseded by ${by.join(', ')}` : word;
}

/** The title without its "ADR 0012 · " / "0012 — " / "ADR 0012: " prefix. */
function titleOf(text, num) {
  const line = /^# (.*)$/m.exec(text)?.[1] ?? '';
  return line.replace(new RegExp(`^(ADR\\s*)?${num}\\s*[·—:-]\\s*`), '').trim();
}

const files = readdirSync(dir).filter(f => /^\d{4}-.*\.md$/.test(f)).sort();
const seen = new Map();
const lines = files.map(f => {
  const num = f.slice(0, 4);
  seen.set(num, [...(seen.get(num) ?? []), f]);
  const text = readFileSync(path.join(dir, f), 'utf8');
  const header = text.split(/^## /m)[0];
  return `- [${num}](${f}) ${titleOf(text, num)} — ${statusOf(header)}`;
});
const dupes = [...seen].filter(([, fs]) => fs.length > 1);

const index = [
  '<!-- Generated by scripts/adr-index.mjs from the ADR files: do not edit by hand, run `node scripts/adr-index.mjs`.',
  'One line per decision record (number, title, status) so agents find the current decision quickly. -->',
  '# Architecture decision records',
  '',
  'Status is read from each file\'s "Status:" line: "superseded by N" means the whole record is replaced; "partly',
  'superseded by N" means the named parts are (the record says which); "not stated" means it has no Status line.',
  'Numbers are unique (`node scripts/adr-index.mjs --check` fails otherwise). The designs numbered 0069 (agent packs)',
  'and 0070 (Battito) were kept outside this repo: references to ADR 0069 have no file here, 0070 only its addendum.',
  '',
  ...lines,
  '',
].join('\n');

if (process.argv.includes('--check')) {
  const stale = !existsSync(out) || readFileSync(out, 'utf8') !== index;
  for (const [num, fs] of dupes) console.error(`ADR ${num} is used by ${fs.join(', ')}`);
  if (stale) console.error('docs/adr/README.md is stale: run node scripts/adr-index.mjs');
  process.exit(stale || dupes.length ? 1 : 0);
}
for (const [num, fs] of dupes) console.warn(`warning: ADR ${num} is used by ${fs.join(', ')}`);
writeFileSync(out, index);
console.log(`docs/adr/README.md: ${lines.length} ADRs`);
