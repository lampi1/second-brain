/** Writes the demo home once (an existing file is left as the user changed it in the demo) and returns it. */
export function demoSkillsHome(userData: string): string {
  const home = path.join(userData, 'demo-home');
  for (const [rel, text] of Object.entries(FILES)) {
    const f = path.join(home, rel);
    if (fs.existsSync(f)) continue;
    fs.mkdirSync(path.dirname(f), { recursive: true });
    fs.writeFileSync(f, text, 'utf8');
  }
  return home;
}
