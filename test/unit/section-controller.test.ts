// Private synthetic registry and human-review callback exercise revision, provenance and explicit-source boundaries.
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { afterEach, expect, it } from 'vitest';
import { SectionController } from '../../src/main/extensions/controller';
import fixture from '../fixtures/extensions/pratiche.json';
const roots: string[] = [];
const root = () => { const value = fs.mkdtempSync(path.join(os.tmpdir(), 'sb-section-controller-')); roots.push(value); return value; };
afterEach(() => { for (const value of roots.splice(0)) fs.rmSync(value, { recursive: true, force: true }); });
const fact = { id: 'work', key: 'work', value: 'Prepare clear meeting notes', category: 'profile' as const };
it('persists a table, rejects stale/malformed mutations, removes and rolls back after reload', () => {
  const directory = root(), controller = new SectionController(directory, async () => false);
  expect(controller.list()).toEqual({ revision: 0, sections: [] });
  expect(controller.register({ manifest: fixture, expectedRevision: 0 }).revision).toBe(1);
  expect(() => controller.remove({ id: fixture.id, expectedRevision: -1 })).toThrow();
  expect(() => controller.remove({ id: fixture.id, expectedRevision: 0 })).toThrow();
  expect(controller.remove({ id: fixture.id, expectedRevision: 1 }).sections).toEqual([]);
  expect(new SectionController(directory, async () => false).rollback({ targetRevision: 1, expectedRevision: 2 }).sections).toEqual([fixture]);
});
it('does not infer setup facts and persists only the exact human-confirmed memory, including cancellation and clear', async () => {
  const directory = root(); let accept = false; const shown: string[] = [];
  const controller = new SectionController(directory, async text => { shown.push(text); return accept; });
  expect(controller.context({ ids: [] }).text).toBe('');
  expect(await controller.saveContext({ facts: [fact], expectedRevision: 0 })).toBeNull();
  expect(controller.archive().revision).toBe(0);
  accept = true; await controller.saveContext({ facts: [fact], expectedRevision: 0 });
  expect(shown).toContain('work: Prepare clear meeting notes');
  const restored = new SectionController(directory, async () => true);
  expect(restored.context({ ids: [] }).text).toContain(fact.value);
  expect(restored.archive().provenance?.source).toBe('explicit-user-confirmation');
  await expect(restored.saveContext({ facts: [{ ...fact, confirmation: 'confirmed' }], expectedRevision: 1 })).rejects.toThrow();
  await restored.saveContext({ facts: [], expectedRevision: 1 });
  expect(restored.context({ ids: [] }).text).toBe('');
});
it('resolves only registered explicit sources and requires review for a one-shot context packet', async () => {
  const directory = root(); let accept = false;
  const controller = new SectionController(directory, async () => accept);
  controller.register({ manifest: fixture, expectedRevision: 0 });
  const inspect = controller.context({ ids: [fixture.id] });
  expect(inspect.pending.length).toBeGreaterThan(0); expect(inspect.unavailable).toEqual([]);
  expect(inspect.text).toBe('');
  expect(controller.context({ ids: ['missing'] }).unavailable).toEqual(['missing']);
  expect(() => controller.context({ ids: ['../../outside'] })).toThrow();
  expect(await controller.requestedContext({ ids: [fixture.id] })).toBeNull();
  accept = true;
  const packet = await controller.requestedContext({ ids: [fixture.id] });
  expect(packet?.text).toContain(fixture.title); expect(packet?.bytes).toBeLessThanOrEqual(4096);
  expect(controller.context({ ids: [fixture.id] }).pending.length).toBeGreaterThan(0);
  expect(controller.archive().facts).toEqual([]);
});
it('revalidates source revisions after native review and refuses concurrent memory confirmations', async () => {
  const directory = root(); let reply: (answer: boolean) => void = () => {};
  const controller = new SectionController(directory, () => new Promise<boolean>(resolve => { reply = resolve; }));
  controller.register({ manifest: fixture, expectedRevision: 0 });
  const pending = controller.requestedContext({ ids: [fixture.id] });
  await expect(controller.saveContext({ facts: [fact], expectedRevision: 0 })).rejects.toThrow('BUSY');
  controller.remove({ id: fixture.id, expectedRevision: 1 }); reply(true);
  await expect(pending).rejects.toThrow('SOURCE_CHANGED');
});
