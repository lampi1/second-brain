// Unit tests of the skills section's main side (src/main/skills): the catalog (user and project folders of Claude and
// Cursor, worktrees and plugin folders left out, generated copies read-only), save (checks, new place, rename moves
// the folder, conflicts, stale file, the hook guard), delete, the "/" fallback; guard.ts against a real hook script;
// toCommands (engine lists → ChatCommand); lib/slash.ts (the input's "/" list).
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { describe, expect, it } from 'vitest';
import { SkillsService } from '../../src/main/skills/service';
import { checkWrite, matches, refusal } from '../../src/main/skills/guard';
import { toCommands } from '../../src/main/chats/session';
import { applyCommand, filterCommands, slashQuery } from '../../src/renderer/lib/slash';

const md = (name: string, desc = 'Una descrizione.', body = 'Corpo.') => `---\nname: ${name}\ndescription: ${desc}\n---\n\n${body}\n`;
function put(root: string, rel: string, text: string): string {
  const f = path.join(root, rel);
  fs.mkdirSync(path.dirname(f), { recursive: true });
  fs.writeFileSync(f, text);
  return f;
}
function fixture() {
  const home = fs.mkdtempSync(path.join(os.tmpdir(), 'sb-skills-home-'));
  const proj = fs.mkdtempSync(path.join(os.tmpdir(), 'sb-skills-proj-'));
  const wt = fs.mkdtempSync(path.join(os.tmpdir(), 'sb-skills-wt-'));
  put(home, '.claude/skills/rivedi/SKILL.md', md('rivedi'));
  put(home, '.claude/skills/rivedi/script.sh', 'echo hi');
  put(home, '.claude/skills/synced/x/SKILL.md', md('x'));
  put(home, '.claude/agents/tester.md', md('tester'));
  put(home, '.claude/agents/copia.md', `${md('copia')}<!-- Generated by sync-agents.mjs from .claude/agents/copia.md, do not edit -->\n`);
  put(home, '.claude/agents/notes.txt', 'not an agent');
  put(home, '.cursor/skills/spiega/SKILL.md', md('spiega'));
  put(proj, '.claude/skills/locale/SKILL.md', md('locale'));
  put(proj, '.cursor/agents/rotto.md', '---\nname: Rotto!\n---\n');
  put(wt, '.claude/skills/locale/SKILL.md', md('locale'));
  fs.writeFileSync(path.join(wt, '.git'), 'gitdir: elsewhere');
  const trashed: string[] = [];
  const svc = new SkillsService({ home, roots: () => [proj, wt, home, null, proj], guard: async () => null, trash: async p => { trashed.push(p); fs.rmSync(p, { recursive: true, force: true }); } });
  return { home, proj, svc, trashed };
}

describe('SkillsService catalog', () => {
  it('lists user and project skills and agents of both engines, without worktrees, plugin folders or non-md files', () => {
    const { svc, proj } = fixture();
    const c = svc.list();
    const names = c.entries.map(e => `${e.harness}/${e.scope}/${e.kind}/${e.name}`).sort();
    expect(names).toEqual(['claude/project/skill/locale', 'claude/user/agent/copia', 'claude/user/agent/tester', 'claude/user/skill/rivedi', 'cursor/project/agent/Rotto!', 'cursor/user/skill/spiega']);
    expect(c.entries.find(e => e.name === 'copia')?.readOnly).toMatch(/sync-agents\.mjs/);
    expect(c.entries.find(e => e.name === 'Rotto!')?.errors).toBe(2); // bad name + no description
    expect(c.entries.find(e => e.name === 'locale')?.root).toBe(path.resolve(proj));
    // places: 2 kinds x 2 engines x (user + 1 project)
    expect(c.places).toHaveLength(8);
  });
});

describe('SkillsService save and delete', () => {
  it('creates a new skill in a place, refuses errors and duplicates', async () => {
    const { svc, home } = fixture();
    const bad = await svc.save({ kind: 'skill', harness: 'claude', scope: 'user', text: md('Bad Name') });
    expect(bad).toMatchObject({ ok: false, error: /errori/ });
    const r = await svc.save({ kind: 'skill', harness: 'claude', scope: 'user', text: md('nuova') });
    expect(r.ok).toBe(true);
    expect(fs.readFileSync(path.join(home, '.claude/skills/nuova/SKILL.md'), 'utf8')).toBe(md('nuova'));
    const dup = await svc.save({ kind: 'skill', harness: 'claude', scope: 'user', text: md('nuova') });
    expect(dup).toMatchObject({ ok: false, error: /Esiste già/ });
  });
  it('edits in place, moves a renamed skill folder with its files, renames an agent file', async () => {
    const { svc, home } = fixture();
    const id = path.join(home, '.claude/skills/rivedi/SKILL.md');
    const doc = svc.read(id);
    const r = await svc.save({ id, mtime: doc.entry.mtime, kind: 'skill', harness: 'claude', scope: 'user', text: md('rivedi-pr', 'Nuova.') });
    expect(r.ok).toBe(true);
    expect(fs.existsSync(path.join(home, '.claude/skills/rivedi'))).toBe(false);
    expect(fs.readFileSync(path.join(home, '.claude/skills/rivedi-pr/script.sh'), 'utf8')).toBe('echo hi');
    const a = path.join(home, '.claude/agents/tester.md');
    expect((await svc.save({ id: a, kind: 'agent', harness: 'claude', scope: 'user', text: md('tester-2') })).ok).toBe(true);
    expect(fs.existsSync(a)).toBe(false);
    expect(fs.existsSync(path.join(home, '.claude/agents/tester-2.md'))).toBe(true);
  });
  it('a file named otherwise than its "name" stays where it is when the name does not change', async () => {
    const { svc, home } = fixture();
    const id = put(home, '.claude/skills/my_skill/SKILL.md', md('my-skill'));
    expect((await svc.save({ id, kind: 'skill', harness: 'claude', scope: 'user', text: md('my-skill', 'Nuova.') })).ok).toBe(true);
    expect(fs.readFileSync(id, 'utf8')).toBe(md('my-skill', 'Nuova.'));
    expect(fs.existsSync(path.join(home, '.claude/skills/my-skill'))).toBe(false);
  });
  it('never overwrites a file changed on disk, a generated copy, or a path outside the folders', async () => {
    const { svc, home } = fixture();
    const id = path.join(home, '.claude/skills/rivedi/SKILL.md');
    const stale = await svc.save({ id, mtime: fs.statSync(id).mtimeMs - 10_000, kind: 'skill', harness: 'claude', scope: 'user', text: md('rivedi', 'x') });
    expect(stale).toMatchObject({ ok: false, error: /cambiato su disco/ });
    const ro = await svc.save({ id: path.join(home, '.claude/agents/copia.md'), kind: 'agent', harness: 'claude', scope: 'user', text: md('copia', 'x') });
    expect(ro).toMatchObject({ ok: false, error: /Copia generata/ });
    const out = await svc.save({ id: path.join(home, 'me.md'), kind: 'agent', harness: 'claude', scope: 'user', text: md('me') });
    expect(out).toMatchObject({ ok: false, error: /cartella conosciuta/ });
    expect(() => svc.read(path.join(home, '.claude', 'settings.json'))).toThrow(/cartella conosciuta/);
    expect(await svc.remove(path.join(home, '.claude/skills/synced/x/SKILL.md'))).toMatchObject({ ok: false });
  });
  it('a hook refusal stops the write and comes back with its message', async () => {
    const home = fs.mkdtempSync(path.join(os.tmpdir(), 'sb-skills-home-'));
    const seen: string[] = [];
    const svc = new SkillsService({ home, roots: () => [], trash: async () => {}, guard: async g => { seen.push(g.filePath); return { command: 'node limits.mjs', message: 'Fixed context over budget' }; } });
    const r = await svc.save({ kind: 'agent', harness: 'cursor', scope: 'user', text: md('nuovo') });
    expect(r).toEqual({ ok: false, error: 'Fixed context over budget', hook: 'node limits.mjs' });
    expect(seen).toEqual([path.join(home, '.cursor', 'agents', 'nuovo.md')]);
    expect(fs.existsSync(seen[0]!)).toBe(false);
  });
  it('deletes a skill folder or an agent file through trash', async () => {
    const { svc, home, trashed } = fixture();
    expect(await svc.remove(path.join(home, '.claude/skills/rivedi/SKILL.md'))).toEqual({ ok: true });
    expect(await svc.remove(path.join(home, '.claude/agents/tester.md'))).toEqual({ ok: true });
    expect(trashed).toEqual([path.join(home, '.claude/skills/rivedi'), path.join(home, '.claude/agents/tester.md')]);
  });
  it('gives the "/" fallback: the engine\'s valid skills for the chat folder', () => {
    const { svc, proj, home } = fixture();
    expect(svc.commandsFor('claude', path.join(proj, 'sub')).map(c => c.name).sort()).toEqual(['locale', 'rivedi']);
    expect(svc.commandsFor('claude', home).map(c => c.name)).toEqual(['rivedi']);
    expect(svc.commandsFor('cursor', proj).map(c => c.name)).toEqual(['spiega']);
  });
});

describe('guard: the user\'s PreToolUse hooks for Write', () => {
  it('matches like Claude Code', () => {
    expect(matches('Edit|Write|MultiEdit', 'Write')).toBe(true);
    expect(matches('Bash|PowerShell', 'Write')).toBe(false);
    expect(matches('', 'Write')).toBe(true);
    expect(matches('*', 'Write')).toBe(true);
    expect(matches('Writer', 'Write')).toBe(false);
  });
  it('reads exit 2 and JSON decisions; other failures do not block', () => {
    expect(refusal(2, '', 'over budget\n')).toBe('over budget');
    expect(refusal(0, '{"decision":"block","reason":"no"}', '')).toBe('no');
    expect(refusal(0, '{"hookSpecificOutput":{"permissionDecision":"deny","permissionDecisionReason":"nope"}}', '')).toBe('nope');
    expect(refusal(0, '{"hookSpecificOutput":{"permissionDecision":"allow"}}', '')).toBeNull();
    expect(refusal(0, '{"hookSpecificOutput":{"permissionDecision":"ask","permissionDecisionReason":"sure?"}}', '')).toBe('sure?'); // no one to ask: refused
    expect(refusal(1, '', 'crash')).toBeNull();
    expect(refusal(0, 'plain text', '')).toBeNull();
  });
  it('runs a real hook with the Write input on stdin', async () => {
    const home = fs.mkdtempSync(path.join(os.tmpdir(), 'sb-guard-'));
    const hook = put(home, 'hook.mjs', `let d='';process.stdin.on('data',c=>d+=c).on('end',()=>{const j=JSON.parse(d);if(j.tool_name==='Write'&&j.tool_input.content.includes('VIETATO')){console.error('No: '+j.tool_input.file_path.split(/[\\\\/]/).pop());process.exit(2)}process.exit(0)})`);
    put(home, '.claude/settings.json', JSON.stringify({ hooks: { PreToolUse: [{ matcher: 'Bash', hooks: [{ type: 'command', command: 'exit 2' }] }, { matcher: 'Edit|Write', hooks: [{ type: 'command', command: `node "${hook.replace(/\\/g, '/')}"`, timeout: 20 }] }] } }));
    expect(await checkWrite({ home, root: null, filePath: path.join(home, 'a', 'SKILL.md'), content: 'ok' })).toBeNull();
    expect(await checkWrite({ home, root: null, filePath: path.join(home, 'a', 'SKILL.md'), content: 'VIETATO' })).toEqual({ command: `node "${hook.replace(/\\/g, '/')}"`, message: 'No: SKILL.md' });
  }, 30_000);
  it('a matching hook it cannot run (type prompt) refuses, never a silent bypass', async () => {
    const home = fs.mkdtempSync(path.join(os.tmpdir(), 'sb-guard-'));
    put(home, '.claude/settings.json', JSON.stringify({ hooks: { PreToolUse: [{ matcher: 'Write', hooks: [{ type: 'prompt', prompt: 'deny big files' }] }] } }));
    expect((await checkWrite({ home, root: null, filePath: path.join(home, 'a', 'SKILL.md'), content: 'ok' }))?.message).toMatch(/tipo "prompt"/);
  });
});

describe('toCommands', () => {
  it('maps Claude and ACP lists, drops untypeable names, marks skills', () => {
    expect(toCommands([
      { name: 'explain', description: 'Spiega (user)', argumentHint: '<x>' },
      { name: 'compact', description: 'Compatta' },
      { name: 'wiz:scan (MCP)', description: 'x' },
      { name: 'explain', description: 'dup' },
    ], new Set(['compact']))).toEqual([
      { name: 'explain', description: 'Spiega', hint: '<x>', skill: true },
      { name: 'compact', description: 'Compatta', skill: true },
    ]);
    expect(toCommands([{ name: '/web', description: 'Cerca', input: { hint: 'query' } }])).toEqual([{ name: 'web', description: 'Cerca', hint: 'query' }]);
    expect(toCommands(null)).toEqual([]);
  });
});

describe('slash list', () => {
  const list = [{ name: 'compact', description: 'Compatta' }, { name: 'spiega', description: 'Spiega a domande', skill: true }, { name: 'rivedi-pr', description: 'Rivede', skill: true }];
  it('shows only while the caret is in the first word after "/"', () => {
    expect(slashQuery('/sp', 3)).toBe('sp');
    expect(slashQuery('/', 1)).toBe('');
    expect(slashQuery('/spiega x', 9)).toBeNull();
    expect(slashQuery('ciao /sp', 8)).toBeNull();
  });
  it('ranks prefix matches and skills first, then word parts and descriptions', () => {
    expect(filterCommands(list, '').map(c => c.name)).toEqual(['rivedi-pr', 'spiega', 'compact']);
    expect(filterCommands(list, 'pr').map(c => c.name)).toEqual(['rivedi-pr']);
    expect(filterCommands(list, 'domande').map(c => c.name)).toEqual(['spiega']);
    expect(filterCommands(list, 'zzz')).toEqual([]);
  });
  it('replaces the typed word and keeps the rest', () => {
    expect(applyCommand('/sp il bilancio', 'spiega')).toEqual({ text: '/spiega il bilancio', caret: 8 });
    expect(applyCommand('/', 'compact')).toEqual({ text: '/compact ', caret: 9 });
  });
});
